<?php

namespace core\user\controller;

class GoodsController extends BaseUser
{

    protected function inputData()
    {
        parent::inputData(); // TODO: Change the autogenerated stub

        if(empty($this->parameters['alias'])){

            $this->setError();

        }

        $data = $this->getGoods([
            'where' => ['alias' => $this->parameters['alias']],
            'join' => [
                'catalog' => [
                    'on' => ['parent_id' => 'id'],
                    'single' => true
                ]
            ],
            'single' => true
        ]);

        if(!$data){

            $this->setError();

        }

        $additionalGoods = $this->model->getGoods([
            'where' => [
                'visible' => 1,
                'id' => $this->model->get('goods_goods', [
                    'fields' => ['_goods_id'],
                    'where' => ['goods_id' => $data['id']],
                    'return_query' => true
                ])
            ],
            'join' => [
                'catalog' => [
                    'fields' => 'name',
                    'on' => ['parent_id' => 'id'],
                    'single' => true
                ]
            ]
        ]);

        $viewed = [];

        if(!empty($_SESSION['viewed'])){

            $viewed = $this->model->getGoods([
                'where' => [
                    'visible' => 1,
                    'id' => array_keys($_SESSION['viewed']),
                    '!id' => $data['id']
                ],
                'join' => [
                    'catalog' => [
                        'fields' => 'name',
                        'on' => ['parent_id' => 'id'],
                        'single' => true
                    ]
                ]
            ]);

        }

        $_SESSION['viewed'][$data['id']] = true;

        return compact('data', 'additionalGoods', 'viewed');

    }

}