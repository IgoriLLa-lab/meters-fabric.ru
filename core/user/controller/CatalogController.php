<?php

namespace core\user\controller;

use core\user\model\Model;

class CatalogController extends BaseUser
{

    protected function inputData()
    {

        if(!$this->model){

            parent::inputData(); // TODO: Change the autogenerated stub

        }

        $where = ['visible' => 1];

        if(empty($this->parameters['alias'])){

            $where['parent_id'] = null;

        }else{

            $where['alias'] = $this->parameters['alias'];

        }

        $data = $this->model->get('catalog', [
            'where' => $where,
            'limit' => 1,
            'order' => 'menu_position',
            'single' => true
        ]);

        if(!$data){

            $this->setError();

        }

        if(empty($this->parameters['alias']) && empty($_GET['search'])){

            $this->redirect($this->alias(['catalog' => $data['alias']]), 301);

        }

        $catalogFilters = $catalogPrices = $totalCount = $goods = $pages = null;

        $order = [
            'price_asc' => 'Цена по возрастанию',
            'price_desc' => 'Цена по убыванию',
        ];

        if(!isset($data['parent_id']) && empty($_GET['search'])){

            $this->template = TEMPLATE . 'index';

        }else{

            $where = [];

            if(!empty($_GET['catalog']) || (!empty($data['id'] && !empty($this->parameters['alias'])))){

                $where['parent_id'] = $_GET['catalog'] ?? $data['id'];

            }else{

                $date = ['name' => $this->translateEl('Результаты поиска')];

            }

            if(!empty($_GET['search'])){

                $search = new SearchController();

                $search->setSearchParameters([
                    'fields' => ['id'],
                    'orderRows' => [],
                    'noPagination' => true,
                    'returnQuery' => true
                ]);

                $query = $search->searchData()['data'] ?? false;

                if($query){

                    $where['id'] = $query;

                }

            }

            $goods = $this->getGoods([
                'where' => ['parent_id' => $_GET['catalog'] ?? $data['id']],
                'join' => [
                    'catalog' => [
                        'fields' => 'name',
                        'on' => ['parent_id' => 'id'],
                        'single' => true
                    ]
                ]
            ], $catalogFilters, $catalogPrices);

            $pages = $this->model->getPagination();

            $totalCount = $this->model->getTotalCountProperty();

        }

        return compact('data', 'catalogFilters', 'catalogPrices', 'goods', 'pages', 'totalCount', 'order');

    }
    public function getAjaxCatalog($alias = ''){

        if(!$this->model){

            $this->model = Model::instance();

        }

        if($alias){

            $this->parameters['alias'] = $this->clearStr($alias);

        }

        return $this->inputData();

    }


}