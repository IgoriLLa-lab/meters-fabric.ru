<?php

namespace core\user\controller;

class InformationController extends BaseUser
{

    protected function inputData()
    {
        parent::inputData(); // TODO: Change the autogenerated stub

        !$this->table && $this->table = 'information';

        if (empty($this->parameters['alias'])){

            $this->setError();

        }

        $where['alias'] = $this->parameters['alias'];

        if (!empty($this->model->showColumns($this->table)['visible'])){

            $where['visible'] = 1;

        }

        $data = $this->model->get($this->table, [
            'where' => $where,
            'limit' => 1,
            'single' => true
        ]);

        if (!$data){

            $this->setError();

        }

        return compact('data');

    }

    public function specialInformation(){

        return $this->setInfoTable();

    }

    public function clientServices(){

        return $this->setInfoTable();

    }

    public function services(){

        return $this->setInfoTable();

    }

    public function pages(){

        return $this->setInfoTable();

    }


    protected function setInfoTable(){

        $this->table = strtolower(preg_replace('/([^A-Z])([A-Z])/', '$1_$2', debug_backtrace()[1]['function']));

        return $this->inputData();

    }

}