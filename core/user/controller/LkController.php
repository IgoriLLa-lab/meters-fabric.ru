<?php

namespace core\user\controller;

use core\base\exceptions\RouteException;

class LkController extends BaseUser
{

    protected function inputData()
    {
        parent::inputData(); // TODO: Change the autogenerated stub

        $freeAccess = ['delayed'];

        if(!$this->userData){

            if(!$freeAccess || empty($this->parameters['alias']) || !in_array($this->parameters['alias'], $freeAccess)){

                $this->redirect($this->alias());

            }

        }

        $orders = $currentOrder = $delayed = $wishList = null;

        if($this->userData){

            $orders = $this->model->get('orders', [
                'where' => ['visitors_id' => $this->userData['id']],
                'order' => 'date DESC', 
                'join' => [
                    'orders_goods' => [
                        'on' => ['id' => 'orders_id']
                    ],
                    'payments' => [
                        'on' => [
                            'table' => 'orders',
                            'fields' => ['payments_id' => 'id']
                        ],
                        'single' => true
                    ],
                    'delivery' => [
                        'on' => [
                            'table' => 'orders',
                            'fields' => ['delivery_id' => 'id']
                        ],
                        'single' => true
                    ],
                    'orders_statuses' => [
                        'on' => [
                            'table' => 'orders',
                            'fields' => ['orders_statuses_id' => 'id']
                        ],
                        'single' => true
                    ],
                ],
                'join_structure' => true
            ]);

            if($orders){

                foreach ($orders as $key => $item){

                    if(!empty($item['join']['orders_goods'])){

                        foreach ($item['join']['orders_goods'] as $k => $value){

                            $orders[$key]['join']['orders_goods'][$k] = $this->goodsNameWithOffer($value);

                        }

                    }

                }

                if(!empty($this->parameters['current-order'])){

                    $id = $this->clearNum($this->parameters['current-order']);

                    $currentOrder = $orders[$id] ?? null;

                }

            }

        }

        if(!empty($this->parameters['alias'])){

            switch($this->parameters['alias']){

                case 'delayed':

                    $delayed = $this->getDelayed();

                    $this->template = TEMPLATE . 'lk_delayed';

                    break;

                case 'orders':

                    $this->template = TEMPLATE . 'lk_orders';

                    break;

                case 'restate':

                    $this->restateOrder($orders ?? null);

                    break;

            }

        }

        return compact('orders', 'currentOrder', 'delayed', 'wishList');

    }

    protected function restateOrder($orders){

        $id = $this->clearNum($this->parameters['id'] ?? 0);

        if(empty($orders) || empty($id) || empty($orders[$id])){

            throw new RouteException('Пользователь с ID ' . $this->userData['id'] . ' занимается фигней');

        }

        $order = $orders[$id];

        $goods = $order['join']['orders_goods'];

        if(!$goods){

            $this->redirect();

        }

        $success = false;

        foreach ($goods as $item){

            $arr = [
                $item[$this->model->goodsTable . '_id'] ?? 0,
                $item['qty'] ?? 0,
                $item[$this->model->offersTable . '_id'] ?? null,
            ];

            if(!empty($item['corrector'])){

                $arr[] = ['corrector' => $item['corrector']];

            }

            $res = $this->addToCart(...$arr);

            if(!empty($res['success'])){

                $success = true;

            }

        }

        $redirect = $success ? $this->alias('cart') : null;

        $this->redirect($redirect);


    }

    protected function getDelayed($action = 'delayed'){

        if(!empty($_SESSION[$action])){

            $where = [
                'id' => array_keys($_SESSION[$action])
            ];

            if(!empty($this->model->showColumns($this->model->goodsTable)['visible'])){

                $where['visible'] = 1;

            }

            return $this->model->getGoods([
                'where' => $where
            ]);

        }

        return null;

    }

    protected function goodsNameWithOffer($data){

        if(!empty($data[$this->model->offersTable . '_name']) && !empty($data['name'])){

            $data['name'] .= '(' . $data[$this->model->offersTable . '_name'] . ')';

        }

        return $data;

    }

}